#pragma once

#include <pbl/util/bits.h>

/* Register offsets */

#define STM32F4_RTC_TR_OFFSET       0x00
#define STM32F4_RTC_DR_OFFSET       0x04
#define STM32F4_RTC_CR_OFFSET       0x08
#define STM32F4_RTC_ISR_OFFSET      0x0c
#define STM32F4_RTC_PRER_OFFSET     0x10
#define STM32F4_RTC_WUTR_OFFSET     0x14
#define STM32F4_RTC_ALRMAR_OFFSET   0x1c
#define STM32F4_RTC_WPR_OFFSET      0x24
#define STM32F4_RTC_SSR_OFFSET      0x28
#define STM32F4_RTC_ALRMASSR_OFFSET 0x44

/* TR, BCD; ALRMAR has the same time fields */
#define STM32F4_RTC_TR_SEC_MASK  PBL_GENMASK(6, 0)
#define STM32F4_RTC_TR_MIN_MASK  PBL_GENMASK(14, 8)
#define STM32F4_RTC_TR_HOUR_MASK PBL_GENMASK(21, 16)
#define STM32F4_RTC_TR_PM        PBL_BIT(22)

/* DR, BCD */
#define STM32F4_RTC_DR_DAY_MASK   PBL_GENMASK(5, 0)
#define STM32F4_RTC_DR_MONTH_MASK PBL_GENMASK(12, 8)
#define STM32F4_RTC_DR_WDU_MASK   PBL_GENMASK(15, 13)
#define STM32F4_RTC_DR_YEAR_MASK  PBL_GENMASK(23, 16)

/* CR */
#define STM32F4_RTC_CR_WUCKSEL_MASK PBL_GENMASK(2, 0)
/* RTCCLK / 16, RTCCLK / 2 and the 1 Hz clock */
#define STM32F4_RTC_CR_WUCKSEL_DIV16 0U
#define STM32F4_RTC_CR_WUCKSEL_DIV2  3U
#define STM32F4_RTC_CR_WUCKSEL_1HZ   4U
#define STM32F4_RTC_CR_BYPSHAD       PBL_BIT(5)
#define STM32F4_RTC_CR_FMT           PBL_BIT(6)
#define STM32F4_RTC_CR_ALRAE         PBL_BIT(8)
#define STM32F4_RTC_CR_WUTE          PBL_BIT(10)
#define STM32F4_RTC_CR_ALRAIE        PBL_BIT(12)
#define STM32F4_RTC_CR_WUTIE         PBL_BIT(14)

/* ISR */
#define STM32F4_RTC_ISR_ALRAWF PBL_BIT(0)
#define STM32F4_RTC_ISR_WUTWF  PBL_BIT(2)
#define STM32F4_RTC_ISR_RSF    PBL_BIT(5)
#define STM32F4_RTC_ISR_INITF  PBL_BIT(6)
#define STM32F4_RTC_ISR_INIT   PBL_BIT(7)
#define STM32F4_RTC_ISR_ALRAF  PBL_BIT(8)
#define STM32F4_RTC_ISR_WUTF   PBL_BIT(10)
/* Writable bits; flags clear on 0 */
#define STM32F4_RTC_ISR_MASK PBL_GENMASK(16, 0)

/* PRER */
#define STM32F4_RTC_PRER_PREDIV_S_MASK PBL_GENMASK(14, 0)
#define STM32F4_RTC_PRER_PREDIV_A_MASK PBL_GENMASK(22, 16)

/* ALRMAR */
#define STM32F4_RTC_ALRMAR_MSK4 PBL_BIT(31)

/* ALRMASSR */
#define STM32F4_RTC_ALRMASSR_SS_MASK     PBL_GENMASK(14, 0)
#define STM32F4_RTC_ALRMASSR_MASKSS_MASK PBL_GENMASK(27, 24)

/* WPR keys */
#define STM32F4_RTC_WPR_KEY1 0xcaU
#define STM32F4_RTC_WPR_KEY2 0x53U
#define STM32F4_RTC_WPR_LOCK 0xffU
