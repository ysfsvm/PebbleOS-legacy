#pragma once

#include <pbl/util/bits.h>

/* Register offsets */

#define STM32F4_RCC_CR_OFFSET      0x00
#define STM32F4_RCC_PLLCFGR_OFFSET 0x04
#define STM32F4_RCC_CFGR_OFFSET    0x08
/* AHB1, AHB2, AHB3, a gap, APB1 and APB2, one word each */
#define STM32F4_RCC_RSTR_OFFSET(n)       (0x10 + 4 * (n))
#define STM32F4_RCC_RSTR_RESERVED_OFFSET 0x1c
#define STM32F4_RCC_ENR_OFFSET(n)        (0x30 + 4 * (n))
#define STM32F4_RCC_BDCR_OFFSET          0x70
#define STM32F4_RCC_CSR_OFFSET           0x74
#define STM32F4_RCC_DCKCFGR_OFFSET       0x8c

/* Register bit definitions */

#define STM32F4_RCC_PLLCFGR_PLLM_MASK  PBL_GENMASK(5, 0)
#define STM32F4_RCC_PLLCFGR_PLLN_MASK  PBL_GENMASK(14, 6)
#define STM32F4_RCC_PLLCFGR_PLLP_MASK  PBL_GENMASK(17, 16)
#define STM32F4_RCC_PLLCFGR_PLLSRC_HSE PBL_BIT(22)

#define STM32F4_RCC_CFGR_SWS_MASK   PBL_GENMASK(3, 2)
#define STM32F4_RCC_CFGR_SWS_HSI    0U
#define STM32F4_RCC_CFGR_SWS_HSE    1U
#define STM32F4_RCC_CFGR_SWS_PLL    2U
#define STM32F4_RCC_CFGR_HPRE_MASK  PBL_GENMASK(7, 4)
#define STM32F4_RCC_CFGR_PPRE1_MASK PBL_GENMASK(12, 10)
#define STM32F4_RCC_CFGR_PPRE2_MASK PBL_GENMASK(15, 13)

/* AHB1ENR: GPIOAEN at bit 0, a port a bit */
#define STM32F4_RCC_AHB1ENR_GPIOEN(port) PBL_BIT(port)
#define STM32F4_RCC_AHB3ENR_FMCEN        PBL_BIT(0)
#define STM32F4_RCC_APB1ENR_PWREN        PBL_BIT(28)

/* BDCR, in the backup domain */
#define STM32F4_RCC_BDCR_LSEON       PBL_BIT(0)
#define STM32F4_RCC_BDCR_LSERDY      PBL_BIT(1)
#define STM32F4_RCC_BDCR_LSEBYP      PBL_BIT(2)
#define STM32F4_RCC_BDCR_RTCSEL_MASK PBL_GENMASK(9, 8)
#define STM32F4_RCC_BDCR_RTCSEL_LSE  1U
#define STM32F4_RCC_BDCR_RTCEN       PBL_BIT(15)

/* CSR */
#define STM32F4_RCC_CSR_RMVF     PBL_BIT(24)
#define STM32F4_RCC_CSR_BORRSTF  PBL_BIT(25)
#define STM32F4_RCC_CSR_PINRSTF  PBL_BIT(26)
#define STM32F4_RCC_CSR_PORRSTF  PBL_BIT(27)
#define STM32F4_RCC_CSR_SFTRSTF  PBL_BIT(28)
#define STM32F4_RCC_CSR_IWDGRSTF PBL_BIT(29)
#define STM32F4_RCC_CSR_WWDGRSTF PBL_BIT(30)
#define STM32F4_RCC_CSR_LPWRRSTF PBL_BIT(31)

#define STM32F4_RCC_DCKCFGR_TIMPRE PBL_BIT(24)

/* Internal RC oscillator */
#define STM32F4_HSI_HZ 16000000U
