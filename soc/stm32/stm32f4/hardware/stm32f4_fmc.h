#pragma once

#include <pbl/util/bits.h>

/* Register offsets, NOR/PSRAM banks 1 to 4 (n = 0..3) */

#define STM32F4_FMC_BCR_OFFSET(n)  (0x000 + 8 * (n))
#define STM32F4_FMC_BTR_OFFSET(n)  (0x004 + 8 * (n))
#define STM32F4_FMC_BWTR_OFFSET(n) (0x104 + 8 * (n))

/* Register bit definitions */

/* BCR */
#define STM32F4_FMC_BCR_MBKEN     PBL_BIT(0)
#define STM32F4_FMC_BCR_MUXEN     PBL_BIT(1)
#define STM32F4_FMC_BCR_MTYP_MASK PBL_GENMASK(3, 2)
#define STM32F4_FMC_BCR_MTYP_NOR  2U
#define STM32F4_FMC_BCR_MWID_MASK PBL_GENMASK(5, 4)
#define STM32F4_FMC_BCR_MWID_16   1U
#define STM32F4_FMC_BCR_FACCEN    PBL_BIT(6)
#define STM32F4_FMC_BCR_BURSTEN   PBL_BIT(8)
#define STM32F4_FMC_BCR_WAITPOL   PBL_BIT(9)
#define STM32F4_FMC_BCR_WRAPMOD   PBL_BIT(10)
#define STM32F4_FMC_BCR_WAITCFG   PBL_BIT(11)
#define STM32F4_FMC_BCR_WREN      PBL_BIT(12)
#define STM32F4_FMC_BCR_WAITEN    PBL_BIT(13)
#define STM32F4_FMC_BCR_EXTMOD    PBL_BIT(14)
#define STM32F4_FMC_BCR_ASYNCWAIT PBL_BIT(15)
#define STM32F4_FMC_BCR_CBURSTRW  PBL_BIT(19)
#define STM32F4_FMC_BCR_CCLKEN    PBL_BIT(20)

/* BTR and BWTR */
#define STM32F4_FMC_BTR_ADDSET_MASK  PBL_GENMASK(3, 0)
#define STM32F4_FMC_BTR_ADDHLD_MASK  PBL_GENMASK(7, 4)
#define STM32F4_FMC_BTR_DATAST_MASK  PBL_GENMASK(15, 8)
#define STM32F4_FMC_BTR_BUSTURN_MASK PBL_GENMASK(19, 16)
#define STM32F4_FMC_BTR_CLKDIV_MASK  PBL_GENMASK(23, 20)
#define STM32F4_FMC_BTR_DATLAT_MASK  PBL_GENMASK(27, 24)
#define STM32F4_FMC_BTR_ACCMOD_MASK  PBL_GENMASK(29, 28)

/* BWTR reset value */
#define STM32F4_FMC_BWTR_RESET 0x0FFFFFFFU
