#pragma once

#include <pbl/util/bits.h>

/* Register offsets */

#define STM32F4_USART_SR_OFFSET   0x00
#define STM32F4_USART_DR_OFFSET   0x04
#define STM32F4_USART_BRR_OFFSET  0x08
#define STM32F4_USART_CR1_OFFSET  0x0c
#define STM32F4_USART_CR2_OFFSET  0x10
#define STM32F4_USART_CR3_OFFSET  0x14
#define STM32F4_USART_GTPR_OFFSET 0x18

/* SR */
#define STM32F4_USART_SR_PE   PBL_BIT(0)
#define STM32F4_USART_SR_FE   PBL_BIT(1)
#define STM32F4_USART_SR_NF   PBL_BIT(2)
#define STM32F4_USART_SR_ORE  PBL_BIT(3)
#define STM32F4_USART_SR_IDLE PBL_BIT(4)
#define STM32F4_USART_SR_RXNE PBL_BIT(5)
#define STM32F4_USART_SR_TC   PBL_BIT(6)
#define STM32F4_USART_SR_TXE  PBL_BIT(7)

#define STM32F4_USART_DR_MASK PBL_GENMASK(8, 0)

/* BRR */
#define STM32F4_USART_BRR_FRACTION_MASK PBL_GENMASK(3, 0)
#define STM32F4_USART_BRR_MANTISSA_MASK PBL_GENMASK(15, 4)

/* CR1 */
#define STM32F4_USART_CR1_SBK    PBL_BIT(0)
#define STM32F4_USART_CR1_RWU    PBL_BIT(1)
#define STM32F4_USART_CR1_RE     PBL_BIT(2)
#define STM32F4_USART_CR1_TE     PBL_BIT(3)
#define STM32F4_USART_CR1_IDLEIE PBL_BIT(4)
#define STM32F4_USART_CR1_RXNEIE PBL_BIT(5)
#define STM32F4_USART_CR1_TCIE   PBL_BIT(6)
#define STM32F4_USART_CR1_TXEIE  PBL_BIT(7)
#define STM32F4_USART_CR1_PEIE   PBL_BIT(8)
#define STM32F4_USART_CR1_PS     PBL_BIT(9)
#define STM32F4_USART_CR1_PCE    PBL_BIT(10)
#define STM32F4_USART_CR1_WAKE   PBL_BIT(11)
#define STM32F4_USART_CR1_M      PBL_BIT(12)
#define STM32F4_USART_CR1_UE     PBL_BIT(13)
#define STM32F4_USART_CR1_OVER8  PBL_BIT(15)

/* CR2 */
#define STM32F4_USART_CR2_STOP_MASK PBL_GENMASK(13, 12)

/* CR3 */
#define STM32F4_USART_CR3_EIE    PBL_BIT(0)
#define STM32F4_USART_CR3_HDSEL  PBL_BIT(3)
#define STM32F4_USART_CR3_DMAR   PBL_BIT(6)
#define STM32F4_USART_CR3_DMAT   PBL_BIT(7)
#define STM32F4_USART_CR3_RTSE   PBL_BIT(8)
#define STM32F4_USART_CR3_CTSE   PBL_BIT(9)
#define STM32F4_USART_CR3_CTSIE  PBL_BIT(10)
#define STM32F4_USART_CR3_ONEBIT PBL_BIT(11)
