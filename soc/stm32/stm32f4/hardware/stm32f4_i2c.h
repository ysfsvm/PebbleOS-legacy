#pragma once

#include <pbl/util/bits.h>

/* Register offsets */

#define STM32F4_I2C_CR1_OFFSET   0x00
#define STM32F4_I2C_CR2_OFFSET   0x04
#define STM32F4_I2C_OAR1_OFFSET  0x08
#define STM32F4_I2C_OAR2_OFFSET  0x0c
#define STM32F4_I2C_DR_OFFSET    0x10
#define STM32F4_I2C_SR1_OFFSET   0x14
#define STM32F4_I2C_SR2_OFFSET   0x18
#define STM32F4_I2C_CCR_OFFSET   0x1c
#define STM32F4_I2C_TRISE_OFFSET 0x20
#define STM32F4_I2C_FLTR_OFFSET  0x24

/* CR1 */
#define STM32F4_I2C_CR1_PE        PBL_BIT(0)
#define STM32F4_I2C_CR1_SMBUS     PBL_BIT(1)
#define STM32F4_I2C_CR1_SMBTYPE   PBL_BIT(3)
#define STM32F4_I2C_CR1_ENARP     PBL_BIT(4)
#define STM32F4_I2C_CR1_ENPEC     PBL_BIT(5)
#define STM32F4_I2C_CR1_ENGC      PBL_BIT(6)
#define STM32F4_I2C_CR1_NOSTRETCH PBL_BIT(7)
#define STM32F4_I2C_CR1_START     PBL_BIT(8)
#define STM32F4_I2C_CR1_STOP      PBL_BIT(9)
#define STM32F4_I2C_CR1_ACK       PBL_BIT(10)
#define STM32F4_I2C_CR1_POS       PBL_BIT(11)
#define STM32F4_I2C_CR1_PEC       PBL_BIT(12)
#define STM32F4_I2C_CR1_ALERT     PBL_BIT(13)
#define STM32F4_I2C_CR1_SWRST     PBL_BIT(15)

/* CR2 */
#define STM32F4_I2C_CR2_FREQ_MASK PBL_GENMASK(5, 0)
#define STM32F4_I2C_CR2_ITERREN   PBL_BIT(8)
#define STM32F4_I2C_CR2_ITEVTEN   PBL_BIT(9)
#define STM32F4_I2C_CR2_ITBUFEN   PBL_BIT(10)
#define STM32F4_I2C_CR2_DMAEN     PBL_BIT(11)
#define STM32F4_I2C_CR2_LAST      PBL_BIT(12)

/* OAR1 */
#define STM32F4_I2C_OAR1_ADD_MASK PBL_GENMASK(9, 0)
#define STM32F4_I2C_OAR1_BIT14    PBL_BIT(14)
#define STM32F4_I2C_OAR1_ADDMODE  PBL_BIT(15)

/* SR1 */
#define STM32F4_I2C_SR1_SB       PBL_BIT(0)
#define STM32F4_I2C_SR1_ADDR     PBL_BIT(1)
#define STM32F4_I2C_SR1_BTF      PBL_BIT(2)
#define STM32F4_I2C_SR1_ADD10    PBL_BIT(3)
#define STM32F4_I2C_SR1_STOPF    PBL_BIT(4)
#define STM32F4_I2C_SR1_RXNE     PBL_BIT(6)
#define STM32F4_I2C_SR1_TXE      PBL_BIT(7)
#define STM32F4_I2C_SR1_BERR     PBL_BIT(8)
#define STM32F4_I2C_SR1_ARLO     PBL_BIT(9)
#define STM32F4_I2C_SR1_AF       PBL_BIT(10)
#define STM32F4_I2C_SR1_OVR      PBL_BIT(11)
#define STM32F4_I2C_SR1_PECERR   PBL_BIT(12)
#define STM32F4_I2C_SR1_TIMEOUT  PBL_BIT(14)
#define STM32F4_I2C_SR1_SMBALERT PBL_BIT(15)

/* SR2 */
#define STM32F4_I2C_SR2_MSL  PBL_BIT(0)
#define STM32F4_I2C_SR2_BUSY PBL_BIT(1)
#define STM32F4_I2C_SR2_TRA  PBL_BIT(2)

/* CCR */
#define STM32F4_I2C_CCR_CCR_MASK PBL_GENMASK(11, 0)
#define STM32F4_I2C_CCR_DUTY     PBL_BIT(14)
#define STM32F4_I2C_CCR_FS       PBL_BIT(15)

/* TRISE */
#define STM32F4_I2C_TRISE_MASK PBL_GENMASK(5, 0)
