#pragma once

#include <pbl/util/bits.h>

/* Register offsets */

#define STM32F4_SPI_CR1_OFFSET     0x00
#define STM32F4_SPI_CR2_OFFSET     0x04
#define STM32F4_SPI_SR_OFFSET      0x08
#define STM32F4_SPI_DR_OFFSET      0x0c
#define STM32F4_SPI_CRCPR_OFFSET   0x10
#define STM32F4_SPI_RXCRCR_OFFSET  0x14
#define STM32F4_SPI_TXCRCR_OFFSET  0x18
#define STM32F4_SPI_I2SCFGR_OFFSET 0x1c
#define STM32F4_SPI_I2SPR_OFFSET   0x20

/* CR1 */
#define STM32F4_SPI_CR1_CPHA     PBL_BIT(0)
#define STM32F4_SPI_CR1_CPOL     PBL_BIT(1)
#define STM32F4_SPI_CR1_MSTR     PBL_BIT(2)
#define STM32F4_SPI_CR1_BR_MASK  PBL_GENMASK(5, 3)
#define STM32F4_SPI_CR1_SPE      PBL_BIT(6)
#define STM32F4_SPI_CR1_LSBFIRST PBL_BIT(7)
#define STM32F4_SPI_CR1_SSI      PBL_BIT(8)
#define STM32F4_SPI_CR1_SSM      PBL_BIT(9)
#define STM32F4_SPI_CR1_RXONLY   PBL_BIT(10)
#define STM32F4_SPI_CR1_DFF      PBL_BIT(11)
#define STM32F4_SPI_CR1_CRCNEXT  PBL_BIT(12)
#define STM32F4_SPI_CR1_CRCEN    PBL_BIT(13)
#define STM32F4_SPI_CR1_BIDIOE   PBL_BIT(14)
#define STM32F4_SPI_CR1_BIDIMODE PBL_BIT(15)

/* CR1 BR: f_PCLK / 2^(BR + 1) */
#define STM32F4_SPI_CR1_BR_MAX 7U

/* CR2 */
#define STM32F4_SPI_CR2_RXDMAEN PBL_BIT(0)
#define STM32F4_SPI_CR2_TXDMAEN PBL_BIT(1)
#define STM32F4_SPI_CR2_SSOE    PBL_BIT(2)
#define STM32F4_SPI_CR2_FRF     PBL_BIT(4)
#define STM32F4_SPI_CR2_ERRIE   PBL_BIT(5)
#define STM32F4_SPI_CR2_RXNEIE  PBL_BIT(6)
#define STM32F4_SPI_CR2_TXEIE   PBL_BIT(7)

/* SR */
#define STM32F4_SPI_SR_RXNE   PBL_BIT(0)
#define STM32F4_SPI_SR_TXE    PBL_BIT(1)
#define STM32F4_SPI_SR_CHSIDE PBL_BIT(2)
#define STM32F4_SPI_SR_UDR    PBL_BIT(3)
#define STM32F4_SPI_SR_CRCERR PBL_BIT(4)
#define STM32F4_SPI_SR_MODF   PBL_BIT(5)
#define STM32F4_SPI_SR_OVR    PBL_BIT(6)
#define STM32F4_SPI_SR_BSY    PBL_BIT(7)
#define STM32F4_SPI_SR_FRE    PBL_BIT(8)

/* I2SCFGR */
#define STM32F4_SPI_I2SCFGR_I2SE   PBL_BIT(10)
#define STM32F4_SPI_I2SCFGR_I2SMOD PBL_BIT(11)
